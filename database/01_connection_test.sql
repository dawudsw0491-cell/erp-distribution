-- Create temporary connection test table
CREATE TABLE IF NOT EXISTS public.connection_test (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    test_message TEXT NOT NULL,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- Enable Row Level Security
ALTER TABLE public.connection_test
ENABLE ROW LEVEL SECURITY;

-- Allow anonymous and authenticated users to read test data
CREATE POLICY "Allow public read connection test"
ON public.connection_test
FOR SELECT
TO anon, authenticated
USING (true);

-- Insert initial test record
INSERT INTO public.connection_test (test_message)
VALUES ('ERP Distribution - Supabase Connected');